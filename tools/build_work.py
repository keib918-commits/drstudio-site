"""Rebuild the portfolio data and thumbnails for the Dr.Studio website.

Source of truth: G:\\AI Surge\\Dr.Seoul\\files\\youtube_upload_prep\\upload_package.json
(published videos only, i.e. entries with a youtube_video_id).
Outputs (relative to the site root):
  assets/work/<id>.webp   540x960 vertical thumbnails from the package covers
  assets/work/work.json   intermediate list
  assets/js/work-data.js  what the page loads (window.DRSTUDIO_WORK)
Run:  python tools/build_work.py      (then rebuild CSS only if new Tailwind classes were added)
"""
import hashlib
import json
import os
import re

from PIL import Image

SITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PREP = r"G:\AI Surge\Dr.Seoul\files\youtube_upload_prep"
LANG_KO = {'Korean': '한국어', 'Spanish · Mexico': '스페인어 · 멕시코', 'Portuguese · Brazil': '포르투갈어 · 브라질',
           'Indonesian': '인도네시아어', 'Turkish': '터키어', 'French · Québec': '프랑스어 · 퀘벡',
           'German · Switzerland': '독일어 · 스위스', 'English': '영어', 'Hindi': '힌디어'}
CAT = {'40weeks': ('임신 앱', 'PREGNANCY APP'), '40weeks-localized': ('임신 앱', 'PREGNANCY APP'),
       'sogd': ('특산품 직배송', 'SPECIALTY FOOD DELIVERY'), 'sowhat': ('성인 게임', 'ADULTS-ONLY GAME')}


def group_of(pid):
    if pid.startswith('40W-EP6'):
        return '40weeks-localized'
    if pid.startswith('40W'):
        return '40weeks'
    if pid.startswith('SOGD'):
        return 'sogd'
    return 'sowhat'


def main():
    pkg = json.load(open(os.path.join(PREP, 'upload_package.json'), encoding='utf-8'))
    os.makedirs(os.path.join(SITE, 'assets', 'work'), exist_ok=True)
    work, data = [], []
    for a in pkg:
        if not a.get('youtube_video_id'):
            continue
        fn = a['id'].lower() + '.webp'
        im = Image.open(os.path.join(PREP, a['cover'])).convert('RGB').resize((540, 960), Image.LANCZOS)
        im.save(os.path.join(SITE, 'assets', 'work', fn), 'WEBP', quality=78, method=6)
        # cache-busting version = content hash, so browsers refetch only when the image really changed
        ver = hashlib.md5(open(os.path.join(SITE, 'assets', 'work', fn), 'rb').read()).hexdigest()[:8]
        fn_v = fn + '?v=' + ver
        title = a['title']
        client = title.split(' — ')[0]
        name = title.split(' — ', 1)[1].split(' | ')[0]
        lang = re.findall(r"\(([^)]*)\)", title)[-1].split(',')[0].strip()
        story = re.search(r"Story (\d/\d)", title)
        g = group_of(a['id'])
        secs = int(round(a['duration_s']))
        item = dict(id=a['id'], yt=a['youtube_video_id'], client=client, title=name, lang=lang,
                    story=story.group(1) if story else None, group=g, thumb='assets/work/' + fn_v,
                    age18=a['settings'].get('age_restricted_18', False), dur=a['duration_s'])
        work.append(item)
        data.append(dict(id=item['id'], yt=item['yt'], client=client, title=name, lang_en=lang, lang_ko=LANG_KO.get(lang, lang),
                         story=item['story'], group=g, thumb=item['thumb'], age18=item['age18'],
                         dur='%d:%02d' % (secs // 60, secs % 60), cat_ko=CAT[g][0], cat_en=CAT[g][1]))
    json.dump(work, open(os.path.join(SITE, 'assets', 'work', 'work.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    js = ("/* Generated by tools/build_work.py from upload_package.json. Do not edit by hand. */\n"
          "window.DRSTUDIO_WORK = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
    open(os.path.join(SITE, 'assets', 'js', 'work-data.js'), 'w', encoding='utf-8').write(js)
    # keep the hero images in index.html on the same versioned URLs
    idx_path = os.path.join(SITE, 'index.html')
    html = open(idx_path, encoding='utf-8').read()
    versions = {d['thumb'].split('?')[0]: d['thumb'] for d in data}
    html = re.sub(r'src="(assets/work/[a-z0-9-]+\.webp)(\?v=[0-9a-f]+)?"',
                  lambda m: 'src="' + versions.get(m.group(1), m.group(1)) + '"', html)
    open(idx_path, 'w', encoding='utf-8', newline='').write(html)
    print(len(data), 'videos written')


if __name__ == '__main__':
    main()
